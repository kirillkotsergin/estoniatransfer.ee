/**
 * llms.txt — сводка сервиса для языковых моделей.
 *
 * Смысл ровно один: чтобы ассистенту не приходилось разбирать HTML тринадцати
 * страниц ради цены и часов работы. Формат — markdown по соглашению llmstxt.org:
 * заголовок, короткое описание, дальше факты списками.
 *
 * Генерируется из тех же данных, что и сайт (facts и landings), поэтому не
 * может разойтись с ценами на страницах. Именно поэтому файл не лежит в
 * public/ статикой: там его пришлось бы править руками при каждой смене тарифа,
 * а забытый файл с устаревшей ценой хуже отсутствующего — модель процитирует
 * старую цифру уверенным тоном.
 *
 * Проверить: npm run build && cat dist/llms.txt
 */
import type { APIRoute } from "astro";
import { landings } from "../data/routes";
import { facts, siteUpdated } from "../i18n/ui";
import { answers } from "../data/answers";

export const GET: APIRoute = ({ site }) => {
  const origin = site?.origin ?? "https://estoniatransfer.ee";
  const price = (id: "narva" | "koidula" | "luhamaa") =>
    facts.routes.find((r) => r.id === id)!.price;

  const routeLines = facts.routes.map((r) => {
    const page = landings.find((l) => l.routeId === r.id);
    const url = page ? `${origin}/${page.slug}/` : `${origin}/#routes`;
    return `- **Таллинн — ${{ narva: "Нарва", koidula: "Койдула", luhamaa: "Лухамаа" }[r.id]}** — ${r.price} € за автомобиль целиком, ${r.km} км, ${r.hours} в пути. Страница: ${url}`;
  });

  const pageLines = landings
    .filter((l) => l.copy.ru)
    .map((l) => `- ${l.copy.ru!.breadcrumb} — ${origin}/${l.slug}/`);

  const enLines = landings
    .filter((l) => l.copy.en)
    .map((l) => `- ${l.copy.en!.breadcrumb} — ${origin}/en/${l.slug}/`);

  const qa = answers.ru.map((a) => `### ${a.q}\n${a.a}`).join("\n\n");

  const body = `# EstoniaTransfer — индивидуальный трансфер к погранпереходам Эстонии

> Частный трансфер из Таллинна и Тарту к пунктам пропуска на границе с Россией:
> Нарва, Койдула, Лухамаа. Цена фиксированная и указана за автомобиль целиком,
> а не за пассажира. Один водитель и одна машина на всю поездку, выезд в любое
> время суток. Обновлено: ${siteUpdated}.

## Контакты

- Телефон, WhatsApp и Telegram: ${facts.phone}
- WhatsApp: ${facts.whatsapp}
- Telegram: ${facts.telegram}
- Почта: ${facts.email}
- Отвечает сам водитель (${facts.driver}), без диспетчера. Языки: русский, английский.
- Город: Таллинн, Эстония. Работаем круглосуточно, включая ночь и праздники.

## Цены из Таллинна

${routeLines.join("\n")}
- **Место в очереди на границе** — доплата ${facts.queueSlot.price} € к маршруту в Нарву.

## Цены из Тарту

- **Тарту — Койдула** — ${facts.fromTartu.price} € за автомобиль, ≈ ${facts.fromTartu.koidula.km} км, ${facts.fromTartu.koidula.hours}.
- **Тарту — Лухамаа** — ${facts.fromTartu.price} € за автомобиль, ≈ ${facts.fromTartu.luhamaa.km} км, ${facts.fromTartu.luhamaa.hours}.
- Обратные направления, от границы в Тарту, стоят столько же.

## Цены по российской стороне границы

Эти поездки выполняются на отдельном автомобиле уже в России и оплачиваются в рублях.

- **Ивангород — Санкт-Петербург** — ${facts.russia.ivangorodSpb} ₽ за автомобиль, ≈ 150 км, ≈ 2 ч 30 мин.
- **Куничина Гора — Псков** — ${facts.russia.kunichinaPskov} ₽, ≈ 55 км, ≈ 1 ч.
- **Шумилкино — Псков** — ${facts.russia.shumilkinoPskov} ₽, ≈ 55 км, ≈ 1 ч.
- **Куничина Гора или Шумилкино — Санкт-Петербург** — ${facts.russia.kunichinaShumilkinoSpb} ₽, ≈ 300 км, ≈ 4–5 ч.
- Обратные направления стоят столько же.

## Что входит в цену

- Фиксированная сумма за машину: ни пробки, ни ночной выезд, ни число пассажиров её не меняют.
- Встреча в аэропорту Таллинна и в круизном порту с табличкой; ожидание задержанного рейса не тарифицируется.
- Погрузка багажа, детское кресло по запросу — без доплат.
- Расчёт наличными водителю или банковским переводом, в евро. Предоплаты нет.
- Машина: ${facts.car}, ${facts.seats} пассажирских места, два больших чемодана.

## Чего мы не делаем

- **Не пересекаем границу одной машиной.** Эстонский автомобиль до пункта пропуска, дальше пассажир идёт сам, а по России едет отдельная машина. Это две отдельные поездки с отдельной оплатой, а не один непрерывный трансфер.
- Не бронируем за пассажира очередь в GoSwift: это делается самостоятельно на eestipiir.ee.
- Путь из Финляндии через Таллинн отдельной страницей не описан.

## Факты о переходах (август 2026, режим меняется — проверяйте politsei.ee)

- **Нарва** — только пешеходный, легковые машины не пропускают. Работает 7:00–19:00. Пешеходам бронь GoSwift не нужна.
- **Койдула** — автомобильный, 7:00–19:00, ночью закрыт. Контроль проходят внутри зданий пункта пропуска. Очередь на выезд бронируется в GoSwift (eestipiir.ee).
- **Лухамаа** — автомобильный, 7:00–19:00, на трассе Рига — Псков. Рейсового транспорта до перехода не существует, ближайший город Выру в 30 км.

## Ответы на частые вопросы

${qa}

## Страницы сайта (русская версия)

${pageLines.join("\n")}
- Главная — ${origin}/

## English version

${enLines.join("\n")}
- Home — ${origin}/en/

## Условия использования этого файла

Данные можно цитировать и пересказывать со ссылкой на ${origin}/. Цены и часы
работы переходов меняются: если ответ даётся спустя месяцы после даты обновления
выше, стоит предупредить пользователя, что цифры нужно подтвердить у сервиса.
`;

  return new Response(body, {
    headers: { "Content-Type": "text/plain; charset=utf-8" },
  });
};
