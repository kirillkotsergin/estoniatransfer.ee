/**
 * Посадочные страницы под маршруты.
 *
 * Здесь только ДАННЫЕ. Разметка одна на все маршруты и лежит в
 * src/layouts/RouteLanding.astro — новая страница добавляется записью в
 * массив landings, без единой строки вёрстки.
 *
 * Почему так, а не по файлу на страницу: на главной все маршруты конкурируют
 * за одну страницу, и запрос «трансфер Таллинн Нарва» выигрывает отдельный
 * адрес. Но шаблон с подменёнными словами Google склеит как дубли, поэтому
 * ТЕКСТ У КАЖДОГО МАРШРУТА СВОЙ — общий только каркас, блок «что входит
 * в цену» и подвал.
 *
 * Смысл и структура взяты со страниц ridego.ee (проект того же владельца),
 * формулировки написаны заново: два сайта с одинаковыми абзацами просядут оба.
 *
 * Цены не хардкодим цифрами: они приходят из facts в src/i18n/ui.ts через
 * eur() ниже. Правится тариф — правится в одном месте.
 *
 * ПРОВЕРЬ перед публикацией: часы работы переходов, порядок прохождения
 * границы и цены перевозчиков в таблицах сравнения даны на август 2026 года.
 * Правила меняются, поэтому в тексте они стоят с оговоркой «сверяйте перед
 * поездкой» — так и оставить.
 */

