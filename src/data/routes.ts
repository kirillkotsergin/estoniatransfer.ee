export type RouteId = (typeof facts.routes)[number]["id"];

/** Цена маршрута строкой. Берётся из facts, чтобы не расходилась с главной. */
const eur = (id: RouteId) => `${facts.routes.find((r) => r.id === id)!.price} €`;
/** Доплата за место в очереди на границе. */
const queue = `${facts.queueSlot.price} €`;
/** Цена из Тарту: одна на оба перехода. */
const tartu = `${facts.fromTartu.price} €`;
/**
 * Запись маршрута из facts целиком — для страниц без routeId. Нужна обратным
 * направлениям: цена, километры и время у них те же, что у поездки из
 * Таллинна, но связывать страницу с facts через routeId нельзя — почему,
 * написано у записи «Нарва — Таллинн».
 */
const spec = (id: RouteId) => facts.routes.find((r) => r.id === id)!;

export interface RouteCopy {
  /** до ~60 знаков: длиннее Google обрежет и начнёт с бренда, а не с ключа */
  title: string;
  /** 140–160 знаков */
  description: string;
  ogDescription?: string;
  /** подпись в крошках и во второй позиции BreadcrumbList */
  breadcrumb: string;
  h1: string;
  lead: string;
  /** подпись под километрами в блоке цифр: «по шоссе», «через Тарту» */
  kmNote?: string;
  /** ярлык над H1. По умолчанию «Маршрут · 160 €» из facts */
  badge?: string;
  /**
   * Три цифры в герое. По умолчанию собираются из facts: цена, время, километры.
   * Задаются руками там, где одной цены на странице нет — например, у сборной
   * страницы с двумя направлениями сразу.
   */
  stats?: { value: string; label: string }[];
  /** Офферы для Service. По умолчанию — цена маршрута из facts (и доплата за очередь) */
  offers?: { name: string; price: string; currency?: string }[];
  /** блок «Коротко» — его цитируют ИИ-поисковики и показывает Google. HTML можно */
  answer: string[];
  /**
   * Предупреждение сразу под блоком «Коротко». Заведено для случая, когда в
   * интернете висит устаревший факт и пассажир может на него попасться:
   * такое нельзя прятать в аккордеон, где до него надо доклкнуть.
   */
  notice?: { title: string; text: string };
  price?: {
    eyebrow: string;
    title: string;
    lead: string;
    caption: string;
    /** услуга · цена · подробности */
    rows: [string, string, string][];
    note: string;
    extra?: { title: string; text: string }[];
  };
  /** отдельный H2 под запрос «трансфер из аэропорта …» — есть не у всех маршрутов */
  airport?: {
    eyebrow: string;
    title: string;
    lead: string;
    items: { title: string; text: string }[];
    cta: string;
    waText: string;
  };
  steps?: { eyebrow: string; title: string; items: { title: string; text: string }[] };
  compare?: {
    eyebrow: string;
    title: string;
    lead: string;
    caption: string;
    cols: string[];
    rows: string[][];
    note: string;
  };
  car?: { eyebrow: string; title: string; caption: string; text: string[] };
  crossing?: { eyebrow: string; title: string; items: { title: string; text: string }[] };
  /**
   * Свободные блоки: набор подробных пунктов с парами «что — сколько» и ссылкой
   * на первоисточник. accordion — когда пунктов много и они длинные (разбор
   * перевозчиков), cards — когда список нужно просматривать глазами (гостиницы).
   */
  blocks?: {
    eyebrow: string;
    title: string;
    lead?: string;
    layout?: "accordion" | "cards";
    /**
     * Заголовки пунктов тегом h3. Нужно там, где пункты — содержание, а не
     * вопросы: у длинных разборов структура H2 → H3 читается поисковиком как
     * оглавление раздела. У FAQ этого не делаем, там своя разметка.
     */
    headings?: boolean;
    /**
     * Где блок стоит в потоке страницы: top — до таблицы наших цен (разбор
     * чужих способов), bottom — после блока про погранпереходы (побочные
     * темы вроде ночлега). По умолчанию top.
     */
    place?: "top" | "bottom";
    items: {
      title: string;
      text: string;
      specs?: [string, string][];
      link?: { label: string; href: string };
    }[];
    note?: string;
  }[];
  /** Список источников в конце: гид ссылается на перевозчиков и politsei.ee */
  sources?: { label: string; href: string }[];
  /**
   * Как страница называется в подвале. Нужна тем страницам, у которых нет
   * routeId: у остальных подпись и цена берутся из facts. Подвал стоит на
   * каждой странице сайта, поэтому это основная перелинковка — новая страница
   * обязана в нём появляться.
   */
  footer?: { label: string; note?: string };
  /** формулировки попадают в FAQPage дословно — они не могут разойтись */
  faq: { eyebrow: string; title: string; items: { q: string; a: string }[] };
  /** перелинковка. href — путь БЕЗ языкового префикса, его добавит шаблон */
  links: { label: string; note?: string; href: string }[];
  cta: { title: string; text: string };
  /** готовый текст сообщения в WhatsApp */
  waText: string;
  schema: {
    name: string;
    alternateName?: string[];
    serviceType: string;
    description: string;
    areaServed: { type: "City" | "Place"; name: string }[];
  };
}

export interface LandingRoute {
  /** адрес страницы: /transfer-tallinn-narva/ */
  slug: string;
  /**
   * route — страница услуги: в микроразметку идёт Service с офферами, в герое
   * стоит блок «что входит в цену».
   * guide — информационная страница: Service там был бы неправдой, поэтому
   * в разметку идёт Article с датой обновления, а коммерческий блок убран.
   */
  kind?: "route" | "guide";
  /** дата последнего обновления фактов, ISO. Идёт в Article.dateModified */
  updated?: string;
  /**
   * Куда страница попадает в подвале. estonia — выезд из Эстонии, russia —
   * поездки по российской стороне за рублями. Разделены не для красоты: это
   * разные услуги с разной валютой, и в одной колонке они путают.
   */
  group?: "estonia" | "russia";
  /**
   * Связь с facts.routes: оттуда цена, километры и время в пути. У сборных
   * страниц, где направлений несколько, его нет — тогда цифры и офферы
   * задаются в copy.stats и copy.offers.
   */
  routeId?: RouteId;
  /** что подставить в форму заявки; по умолчанию Таллинн — Нарва */
  form?: { from: CityId; to: CityId };
  /**
   * Имя файла в src/assets/car без расширения. Идёт в два места сразу: в
   * видимый блок «машина и водитель» — но только если у страницы задан
   * `copy.car`, — и в поле `image` у Product в микроразметке.
   *
   * У российских страниц `copy.car` нет намеренно (эстонская машина границу не
   * пересекает), а `photo` задан: без `image` Search Console помечает страницу
   * критической ошибкой. Выходит фото, которое видно только поисковику.
   */
  photo?: string;
  /** язык добавляется, когда для него написан текст. Нет текста — нет страницы */
  copy: Partial<Record<Lang, RouteCopy>>;
}

