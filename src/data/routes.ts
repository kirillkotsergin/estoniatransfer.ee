/**
 * Английские тексты подмешиваются из отдельного файла: русские блоки выше и так
 * занимают почти всю длину файла, а перевод удобнее держать и править целиком.
 * Ключ в объекте en — slug страницы; чего там нет, того нет и на английском,
 * и тогда страница просто не создаётся (см. landingsFor).
 */
for (const route of landings) {
  const translated = en[route.slug];
  if (translated) route.copy.en = translated;
}

/** Маршруты, для которых на этом языке есть текст. Нет текста — нет страницы. */
export function landingsFor(lang: Lang): LandingRoute[] {
  return landings.filter((r) => r.copy[lang]);
}

/**
 * Ссылки для подвала: маршруты отдельно, информационные страницы отдельно.
 * Собирается из тех же данных, что и сами страницы, поэтому новая запись в
 * landings появляется в подвале сама — забыть её там больше нельзя.
 *
 * Подпись и цена для страниц маршрутов берутся из facts (label приходит
 * из словаря по routeId), для остальных — из copy.footer.
 */
export function footerLinks(lang: Lang, label: (id: RouteId) => string) {
  // Три группы вместо двух: маршруты из Эстонии, поездки по России и статьи.
  const link = (r: LandingRoute) => {
    const copy = r.copy[lang]!;
    if (r.routeId) {
      const f = facts.routes.find((x) => x.id === r.routeId)!;
      return { label: label(r.routeId), note: `${f.price} €`, href: localePath(lang, `/${r.slug}/`) };
    }
    return {
      label: copy.footer?.label ?? copy.breadcrumb,
      note: copy.footer?.note,
      href: localePath(lang, `/${r.slug}/`),
    };
  };

  const pages = landingsFor(lang);
  return {
    routes: pages.filter((r) => r.kind !== "guide" && r.group !== "russia").map(link),
    russia: pages.filter((r) => r.group === "russia").map(link),
    guides: pages.filter((r) => r.kind === "guide").map(link),
  };
}

/** Языки, на которых существует страница: из этого собирается hreflang. */
export function landingLangs(slug: string): Lang[] {
  const found = landings.find((r) => r.slug === slug);
  return found ? (Object.keys(found.copy) as Lang[]) : [];
}

/**
 * Ссылка на посадочную страницу маршрута — для карточек на главной и подвала.
 * Пока текста на нужном языке нет, возвращает null: битых ссылок не будет.
 */
export function landingHref(lang: Lang, routeId: RouteId): string | null {
  const found = landings.find((r) => r.routeId === routeId && r.copy[lang]);
  return found ? localePath(lang, `/${found.slug}/`) : null;
}
