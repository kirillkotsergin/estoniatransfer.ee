/**
 * Посадочные страницы под маршруты.
 *
 * Здесь только ДАННЫЕ. Разметка одна на все маршруты и лежит в
 * src/layouts/RouteLanding.astro — новая страница добавляется записью в
 * массив landings, без единой строки вёрстки.
 *
 * Почему так, а не по файлу на страницу: на главной все маршруты конкурируют
 * за одну страницу, и запрос «трансфер Таллинн Нарва» выигрывает отдельный
 * адрес. Но шаблон с подменёнными словами Google склеит как дубли, поэтому
 * ТЕКСТ У КАЖДОГО МАРШРУТА СВОЙ — общий только каркас, блок «что входит
 * в цену» и подвал.
 *
 * Смысл и структура взяты со страниц ridego.ee (проект того же владельца),
 * формулировки написаны заново: два сайта с одинаковыми абзацами просядут оба.
 *
 * Цены не хардкодим цифрами: они приходят из facts в src/i18n/ui.ts через
 * eur() ниже. Правится тариф — правится в одном месте.
 *
 * ПРОВЕРЬ перед публикацией: часы работы переходов, порядок прохождения
 * границы и цены перевозчиков в таблицах сравнения даны на август 2026 года.
 * Правила меняются, поэтому в тексте они стоят с оговоркой «сверяйте перед
 * поездкой» — так и оставить.
 */

import { facts, localePath, type CityId, type Lang } from "../i18n/ui";

export type RouteId = (typeof facts.routes)[number]["id"];

/** Цена маршрута строкой. Берётся из facts, чтобы не расходилась с главной. */
const eur = (id: RouteId) => `${facts.routes.find((r) => r.id === id)!.price} €`;
/** Доплата за место в очереди на границе. */
const queue = `${facts.queueSlot.price} €`;

export interface RouteCopy {
  /** до ~60 знаков: длиннее Google обрежет и начнёт с бренда, а не с ключа */
  title: string;
  /** 140–160 знаков */
  description: string;
  ogDescription?: string;
  /** подпись в крошках и во второй позиции BreadcrumbList */
  breadcrumb: string;
  h1: string;
  lead: string;
  /** подпись под километрами в блоке цифр: «по шоссе», «через Тарту» */
  kmNote: string;
  /** блок «Коротко» — его цитируют ИИ-поисковики и показывает Google. HTML можно */
  answer: string[];
  price: {
    eyebrow: string;
    title: string;
    lead: string;
    caption: string;
    /** услуга · цена · подробности */
    rows: [string, string, string][];
    note: string;
    extra?: { title: string; text: string }[];
  };
  /** отдельный H2 под запрос «трансфер из аэропорта …» — есть не у всех маршрутов */
  airport?: {
    eyebrow: string;
    title: string;
    lead: string;
    items: { title: string; text: string }[];
    cta: string;
    waText: string;
  };
  steps: { eyebrow: string; title: string; items: { title: string; text: string }[] };
  compare?: {
    eyebrow: string;
    title: string;
    lead: string;
    caption: string;
    cols: string[];
    rows: string[][];
    note: string;
  };
  car: { eyebrow: string; title: string; caption: string; text: string[] };
  crossing: { eyebrow: string; title: string; items: { title: string; text: string }[] };
  /** формулировки попадают в FAQPage дословно — они не могут разойтись */
  faq: { eyebrow: string; title: string; items: { q: string; a: string }[] };
  /** перелинковка. href — путь БЕЗ языкового префикса, его добавит шаблон */
  links: { label: string; note?: string; href: string }[];
  cta: { title: string; text: string };
  /** готовый текст сообщения в WhatsApp */
  waText: string;
  schema: {
    name: string;
    alternateName?: string[];
    serviceType: string;
    description: string;
    areaServed: { type: "City" | "Place"; name: string }[];
  };
}

export interface LandingRoute {
  /** адрес страницы: /transfer-tallinn-narva/ */
  slug: string;
  /** связь с facts.routes: оттуда цена, километры и время в пути */
  routeId: RouteId;
  /** что подставить в форму заявки */
  form: { from: CityId; to: CityId };
  /** имя файла в src/assets/car без расширения */
  photo: string;
  /** язык добавляется, когда для него написан текст. Нет текста — нет страницы */
  copy: Partial<Record<Lang, RouteCopy>>;
}

