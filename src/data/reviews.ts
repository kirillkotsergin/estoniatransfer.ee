/**
 * Отзывы пассажиров.
 *
 * ⚠️ Сюда попадают только **настоящие** отзывы настоящих пассажиров, с их
 * разрешения показать имя. Ни одной выдуманной записи, ни одной «для затравки».
 * Причина не в щепетильности, а в цене вопроса:
 *
 * - Google: «Ratings must be sourced directly from users», «Don't include fake
 *   or undisclosed incentivized reviews on your page or in your structured data
 *   markup». За нарушение накладывают ручные меры, и бьют они по всему сайту, а
 *   не по одной странице — расширенные сниппеты пропадут везде разом.
 * - Закон: с 28.05.2022 в ЕС действует директива Omnibus, и публикация отзывов
 *   с непроверенным происхождением прямо отнесена к запрещённым коммерческим
 *   практикам. Бизнес эстонский, так что это не про позиции в выдаче.
 *
 * Пока массив пуст, на страницах нет ни блока отзывов, ни `aggregateRating`,
 * ни `review` в разметке — ровно как сейчас. Появится первая запись — включится
 * всё сразу, править шаблон не понадобится.
 *
 * Search Console пишет по страницам маршрутов «Missing field aggregateRating».
 * Это **предупреждение, а не ошибка**: у merchant listings `aggregateRating`
 * лежит в разделе рекомендованных полей, а обязательные — `name` и одно из
 * `offers` / `review` / `aggregateRating`. `offers` на страницах есть, право на
 * расширенный сниппет действует. Предупреждение закроется само, когда появятся
 * реальные отзывы, и никак иначе.
 *
 * Как добавить отзыв:
 *   1. Спросить у пассажира разрешение показать имя и текст.
 *   2. Дописать запись в массив ниже. Текст — как написан, без причёсывания:
 *      отзыв, отредактированный до гладкости, читается как рекламный и работает
 *      хуже живого.
 *   3. `route` — slug страницы того маршрута, по которому ехали.
 */
import type { Lang } from "../i18n/ui";

export interface PassengerReview {
  /** slug страницы маршрута: "transfer-tallinn-narva" и т. д. */
  route: string;
  /** имя в том виде, в каком пассажир разрешил его показать */
  author: string;
  /** дата отзыва, YYYY-MM-DD */
  date: string;
  /** целое от 1 до 5 */
  rating: 1 | 2 | 3 | 4 | 5;
  /** язык, на котором отзыв написан; в разметку идёт как inLanguage */
  lang: Lang;
  /** текст отзыва как есть */
  text: string;
}

/**
 * Пусто — и это правильное состояние файла до первого настоящего отзыва.
 *
 * Пример записи, для формата (закомментирован намеренно, раскомментировать
 * можно только заменив на реальный отзыв):
 *
 * {
 *   route: "transfer-tallinn-narva",
 *   author: "Марина",
 *   date: "2026-08-24",
 *   rating: 5,
 *   lang: "ru",
 *   text: "Забрали из аэропорта в пять утра, до Нарвы доехали за два с половиной часа.",
 * },
 */
export const reviews: PassengerReview[] = [];

/** Отзывы одного маршрута, свежие сверху. */
export function reviewsFor(slug: string): PassengerReview[] {
  return reviews
    .filter((r) => r.route === slug)
    .sort((a, b) => b.date.localeCompare(a.date));
}

/**
 * Средняя оценка маршрута. Считается по **всем** отзывам маршрута, независимо
 * от языка страницы: русская и английская версии описывают одну и ту же услугу
 * с одним `@id`, и разные рейтинги на них означали бы два разных факта об одном
 * субъекте. По той же причине отзыв показывается на обеих версиях в оригинале,
 * а не переводится: перевод — это уже не то, что написал пассажир.
 *
 * Возвращает null, когда отзывов нет: вычислять не из чего, и разметки быть
 * не должно.
 */
export function ratingFor(slug: string): { value: string; count: number } | null {
  const list = reviewsFor(slug);
  if (!list.length) return null;
  const sum = list.reduce((acc, r) => acc + r.rating, 0);
  return { value: (sum / list.length).toFixed(1), count: list.length };
}
