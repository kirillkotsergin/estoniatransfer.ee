import { defineConfig, fontProviders } from "astro/config";
import tailwindcss from "@tailwindcss/vite";

// Статическая сборка: Node нужен только здесь, на сервере его нет и не нужно.
// Все страницы всех языков превращаются в готовые HTML-файлы, которые Apache
// отдаёт за ~50 мс. Для SEO это ровно то же, что SSR, только быстрее и без
// процесса, который может умереть.
export default defineConfig({
  site: "https://estoniatransfer.ee",
  output: "static",
  trailingSlash: "always",
  build: {
    // каждая страница — каталог с index.html, поэтому URL без .html
    format: "directory",
    /**
     * Весь CSS уезжает в <style> внутри страницы, отдельного файла нет.
     *
     * Зачем: <link rel="stylesheet"> блокировал первую отрисовку — браузер
     * ждал ещё один круг до сервера прежде чем показать хоть что-то, и это
     * прямо било в LCP. Инлайн убирает этот запрос совсем.
     *
     * Чем платим: 27 КБ (6,6 КБ под gzip) едут с каждой страницей и не
     * кешируются между переходами, тогда как отдельный файл кешировался бы
     * навсегда. Для сайта, куда приходят из поиска сразу на нужную страницу,
     * обмен выгодный. Появится много переходов внутри сайта — вернуть "auto".
     */
    inlineStylesheets: "always",
  },
  i18n: {
    defaultLocale: "ru",
    // ET и FI добавляются сюда же, когда будут переводы: остальной код готов
    locales: ["ru", "en"],
    routing: {
      // русский лежит в корне, английский — в /en/
      prefixDefaultLocale: false,
    },
  },
  /**
   * Фирменный шрифт Onest (02.10.2026) — кириллица и латиница, одним
   * вариативным файлом на подмножество. До этого стоял системный шрифт, и
   * сайт выглядел по-разному на каждом устройстве: Segoe UI, SF Pro, Roboto.
   *
   * Через встроенный Fonts API, а не голым @import CSS из пакета, по двум
   * причинам:
   *  - Astro скачивает файлы при сборке и кладёт их в dist — шрифт
   *    отдаётся со своего домена, как требует CSP (`font-src 'self'`);
   *  - он генерирует подстроенный запасной шрифт (size-adjust по метрикам
   *    Onest), поэтому подмена шрифта при загрузке не сдвигает вёрстку: CLS
   *    остаётся 0. Голый @import этого не умеет.
   *
   * Предзагрузки (preload) нет намеренно: она конкурировала бы за канал с
   * фото в герое, а именно фото теперь самый крупный элемент первого экрана.
   */
  fonts: [
    {
      provider: fontProviders.fontsource(),
      name: "Onest",
      cssVariable: "--font-onest",
      weights: ["100 900"],
      styles: ["normal"],
      subsets: ["cyrillic", "latin"],
      fallbacks: ["sans-serif"],
      display: "swap",
    },
  ],
  vite: {
    plugins: [tailwindcss()],
  },
});
